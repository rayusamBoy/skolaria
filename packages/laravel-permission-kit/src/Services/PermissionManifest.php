<?php

declare(strict_types=1);

namespace PermissionKit\Services;

use Illuminate\Support\Collection;
use PermissionKit\Support\PermissionDefinition;

/**
 * Reads and writes the editable permission manifest.
 *
 * The manifest is a PHP file grouped by context → resource → method so
 * that users can open it in their editor and adjust labels and descriptions
 * without touching the database.
 *
 * ### Format
 *
 *   return [
 *       'default' => [
 *           'users' => [
 *               'index' => [
 *                   'permission'  => 'users.view',
 *                   'label'       => 'View Users List',
 *                   'description' => 'Display a list of all users.',
 *                   'controller'  => 'UserController',
 *                   'method'      => 'index',
 *               ],
 *               // ...
 *           ],
 *       ],
 *       // other contexts
 *   ];
 */
class PermissionManifest
{
    public function __construct(protected string $path) {}

    public function path(): string
    {
        return $this->path;
    }

    public function exists(): bool
    {
        return $this->path !== '' && is_file($this->path);
    }

    /**
     * Load the manifest, returning an empty array when the file doesn't exist.
     *
     * @return array<string, array<string, array<string, array<string, mixed>>>>
     */
    public function load(): array
    {
        if (! $this->exists()) {
            return [];
        }

        $data = require $this->path;

        return \is_array($data) ? $data : [];
    }

    /**
     * Persist definitions to disk. When $merge is true, existing labels and
     * descriptions are preserved — only new entries are added and removed
     * methods are dropped.
     *
     * @param  Collection<int, PermissionDefinition>  $definitions
     */
    public function save(Collection $definitions, bool $merge = true): void
    {
        $existing = $merge ? $this->load() : [];
        $grouped = [];

        foreach ($definitions as $definition) {
            $existing_entry = $this->findInData($existing, $definition->context, $definition->controller, $definition->method);
            $resource = explode('.', $definition->name)[0] ?: 'misc';

            $grouped[$definition->context][$resource][$definition->method] = [
                'permission' => $definition->name,
                'label' => $existing_entry['label'] ?? $definition->label,
                'description' => $existing_entry['description'] ?? $definition->description,
                'controller' => $definition->controller,
                'method' => $definition->method,
            ];
        }

        ksort($grouped);
        foreach ($grouped as &$resources) {
            ksort($resources);
            foreach ($resources as &$methods) {
                ksort($methods);
            }
        }
        unset($resources, $methods);

        $this->ensureDirectoryExists();

        $export = var_export($grouped, true);
        $content = "<?php\n\n"
            ."// Auto-generated by `permission-kit:scan --save`. Safe to edit.\n"
            ."// After editing, run `permission-kit:sync` to push changes to the database.\n\n"
            ."return {$export};\n";

        file_put_contents($this->path, $content);
    }

    /**
     * Look up the permission name for a specific controller method.
     */
    public function find(string $context, string $controller, string $method): ?string
    {
        $entry = $this->findInData($this->load(), $context, $controller, $method);

        return $entry['permission'] ?? null;
    }

    /**
     * Convert the raw manifest array back into definitions for the sync service.
     *
     * @return Collection<int, PermissionDefinition>
     */
    public function toDefinitions(): Collection
    {
        $definitions = collect();

        foreach ($this->load() as $context => $resources) {
            foreach ($resources as $resource => $methods) {
                foreach ($methods as $method => $entry) {
                    $definitions->push(new PermissionDefinition(
                        name: $entry['permission'] ?? "{$resource}.{$method}",
                        label: $entry['label'] ?? null,
                        description: $entry['description'] ?? null,
                        context: $context,
                        controller: $entry['controller'] ?? '',
                        method: $entry['method'] ?? $method,
                    ));
                }
            }
        }

        return $definitions;
    }

    /**
     * @param  array<string, array>  $data
     * @return array<string, mixed>|null
     */
    protected function findInData(array $data, string $context, string $controller, string $method): ?array
    {
        foreach ($data[$context] ?? [] as $methods) {
            foreach ($methods as $entry) {
                if (($entry['controller'] ?? null) === $controller
                    && ($entry['method'] ?? null) === $method) {
                    return $entry;
                }
            }
        }

        return null;
    }

    protected function ensureDirectoryExists(): void
    {
        $dir = dirname($this->path);

        if (! is_dir($dir) && ! mkdir($dir, 0755, true) && ! is_dir($dir)) {
            throw new \RuntimeException("Cannot create directory: {$dir}");
        }
    }
}
