<?php

use PermissionKit\Services\PermissionCollector;
use PermissionKit\Services\PermissionSyncService;
use Spatie\Permission\Models\Permission;

it('creates permissions in spatie table', function () {
    $definitions = app(PermissionCollector::class)->collect();
    $sync = app(PermissionSyncService::class);

    $report = $sync->sync($definitions);

    expect($report->created)->not->toBeEmpty();

    $this->assertDatabaseHas('permissions', ['name' => 'users.view']);
    $this->assertDatabaseHas('permissions', ['name' => 'users.delete']);
});

it('does not duplicate permissions on second sync', function () {
    $definitions = app(PermissionCollector::class)->collect();
    $sync = app(PermissionSyncService::class);

    $sync->sync($definitions);
    $report = $sync->sync($definitions);

    expect($report->created)->toBeEmpty()
        ->and($report->unchanged)->not->toBeEmpty();

    expect(Permission::where('name', 'users.view')->count())->toBe(1);
});

it('supports dry run', function () {
    $definitions = app(PermissionCollector::class)->collect();
    $sync = app(PermissionSyncService::class);

    $report = $sync->sync($definitions, dry_run: true);

    expect($report->created)->not->toBeEmpty();
    $this->assertDatabaseMissing('permissions', ['name' => 'users.view']);
});

it('updates label and description when changed', function () {
    Permission::create(['name' => 'users.view', 'guard_name' => 'web', 'label' => 'Old Label']);

    $definitions = app(PermissionCollector::class)->collect();
    $sync = app(PermissionSyncService::class);

    $sync->sync($definitions, mode: 'update');

    $this->assertDatabaseHas('permissions', [
        'name' => 'users.view',
        'label' => 'Users View', // generated by Str::headline
    ]);
});

it('preserves existing labels in preserve mode', function () {
    Permission::create(['name' => 'users.view', 'guard_name' => 'web', 'label' => 'Custom Label']);

    $definitions = app(PermissionCollector::class)->collect();
    $sync = app(PermissionSyncService::class);

    $sync->sync($definitions, mode: 'preserve');

    $this->assertDatabaseHas('permissions', [
        'name' => 'users.view',
        'label' => 'Custom Label',
    ]);
});

it('runs sync via command', function () {
    $this->artisan('permission-kit:sync')->assertSuccessful();

    $this->assertDatabaseHas('permissions', ['name' => 'users.view']);
});

it('supports dry-run through the command', function () {
    $this->artisan('permission-kit:sync', ['--dry-run' => true])->assertSuccessful();

    $this->assertDatabaseMissing('permissions', ['name' => 'users.view']);
});
